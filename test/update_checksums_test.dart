import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:kazumi/services/update/update_checksums.dart';

void main() {
  group('parseChecksums', () {
    test('parses sha256sum output with one and two spaces', () {
      final sums = parseChecksums(
        '0b8cec731144e5a35b523a0dc8b513957a9c2afb4af08da97347de0e398803a0  app.apk\n'
        'D8351FBA1CD359D6CC8758B4DD6AD8FB4442C2698A9D2259EBDA918238B80685 *setup.exe\n',
      );
      expect(
        sums['app.apk'],
        '0b8cec731144e5a35b523a0dc8b513957a9c2afb4af08da97347de0e398803a0',
      );
      // 大写值统一转小写，与下载器的正则一致。
      expect(
        sums['setup.exe'],
        'd8351fba1cd359d6cc8758b4dd6ad8fb4442c2698a9d2259ebda918238b80685',
      );
    });

    test('handles CRLF and skips comments, blank and malformed lines', () {
      final sums = parseChecksums(
        '# generated by publish script\r\n'
        '\r\n'
        'not-a-hash  app.apk\r\n'
        'abc123  app.apk\r\n'
        '0b8cec731144e5a35b523a0dc8b513957a9c2afb4af08da97347de0e398803a0  app.apk\r\n',
      );
      expect(sums, hasLength(1));
      expect(sums['app.apk'], isNotNull);
    });

    test('matches by file name when the line carries a directory prefix', () {
      final sums = parseChecksums(
        '0b8cec731144e5a35b523a0dc8b513957a9c2afb4af08da97347de0e398803a0  dist/app.apk\n',
      );
      expect(sums['dist/app.apk'], isNotNull);
      expect(sums['app.apk'], isNotNull);
    });
  });

  group('findChecksumAssetUrl', () {
    test('prefers checksums.txt in the same release', () {
      final url = findChecksumAssetUrl([
        {
          'name': 'app.apk',
          'browser_download_url': 'https://codeberg.org/o/r/app.apk',
        },
        {
          'name': 'checksums.txt',
          'browser_download_url': 'https://codeberg.org/o/r/checksums.txt',
        },
      ]);
      expect(url, 'https://codeberg.org/o/r/checksums.txt');
    });

    test('returns null when the release carries no checksum file', () {
      expect(
        findChecksumAssetUrl([
          {'name': 'app.apk', 'browser_download_url': 'https://x/app.apk'},
        ]),
        isNull,
      );
    });
  });

  group('applyChecksums', () {
    test('writes digest onto the matching assets only', () {
      final assets = <dynamic>[
        {'name': 'app.apk', 'browser_download_url': 'https://x/app.apk'},
        {'name': 'other.exe', 'browser_download_url': 'https://x/other.exe'},
      ];
      const hash =
          '0b8cec731144e5a35b523a0dc8b513957a9c2afb4af08da97347de0e398803a0';
      final applied = applyChecksums(assets, {'app.apk': hash});

      expect(applied, 1);
      expect(assets[0]['digest'], 'sha256:$hash');
      expect(assets[1].containsKey('digest'), isFalse);
    });
  });

  group('real Codeberg release payload', () {
    test('matches the published assets and restores their digests', () {
      final payload =
          json.decode(
                File('test/fixtures/codeberg-release.json').readAsStringSync(),
              )
              as Map<String, dynamic>;
      final sums = parseChecksums(
        File('test/fixtures/codeberg-checksums.txt').readAsStringSync(),
      );

      expect(payload['tag_name'], '3.11.0');
      final assets = payload['assets'] as List<dynamic>;
      expect(findChecksumAssetUrl(assets), isNotNull);
      expect(applyChecksums(assets, sums), assets.length - 1);
      final installers = assets.where(
        (asset) => asset['name'] != 'checksums.txt',
      );
      expect(installers.every((asset) => asset['digest'] != null), isTrue);
    });
  });
}